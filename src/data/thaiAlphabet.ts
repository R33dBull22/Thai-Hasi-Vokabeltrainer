// Comprehensive Thai Alphabet, Vowels, and Tone Rules Reference Data

export type ConsonantClass = 'mid' | 'high' | 'low';

export interface ThaiConsonant {
  letter: string;
  nameThai: string;
  namePhonetic: string;
  meaningGerman: string;
  class: ConsonantClass;
  initialSound: string;
  finalSound: string;
  isObsolete?: boolean;
}

export interface ThaiVowel {
  symbol: string;
  nameThai: string;
  phonetic: string;
  length: 'short' | 'long' | 'special';
  isDeadByDefault: boolean;
  exampleWord: string;
  exampleGerman: string;
}

export interface ToneRule {
  class: ConsonantClass;
  classNameGerman: string;
  rules: {
    condition: string;
    tone: 'mid' | 'low' | 'falling' | 'high' | 'rising';
    example: string;
    exampleRom: string;
    meaning: string;
  }[];
}

